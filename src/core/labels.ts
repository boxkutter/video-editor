export type LabelKey = keyof typeof DEFAULT_LABELS;
export type Labels = Record<LabelKey, string>;
export type LabelOverrides = Partial<Labels>;
export type Translate = (key: LabelKey, vars?: Record<string, string | number>) => string;

/** A translate function over the defaults and the host's overrides. */
export function createT(overrides: LabelOverrides = {}): Translate {
  const labels: Labels = { ...DEFAULT_LABELS, ...overrides };
  return (key, vars) => {
    const text = labels[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? "")) : text;
  };
}
